import 'package:flutter/foundation.dart';
import 'package:hive_flutter/hive_flutter.dart';
import 'hive_models/user_model.dart';
import 'hive_models/recent_play_model.dart';
import 'hive_models/bookmark_model.dart';
import 'hive_models/support_ticket_model.dart';
import 'hive_models/notification_model.dart';
import 'hive_models/app_settings_model.dart';
import 'hive_models/downloaded_audio_model.dart';

/// Central Hive Database Manager
/// Manages all Hive boxes and provides singleton access
class HiveDatabase {
  static final HiveDatabase _instance = HiveDatabase._internal();

  factory HiveDatabase() {
    return _instance;
  }

  HiveDatabase._internal();

  // Box names
  static const String userBoxName = 'users';
  static const String recentPlayBoxName = 'recent_plays';
  static const String bookmarkBoxName = 'bookmarks';
  static const String supportTicketBoxName = 'support_tickets';
  static const String notificationBoxName = 'notifications';
  static const String appSettingsBoxName = 'app_settings';
  static const String downloadBoxName = 'downloads';

  // Boxes
  late Box<UserModel> _userBox;
  late Box<RecentPlayModel> _recentPlayBox;
  late Box<BookmarkModel> _bookmarkBox;
  late Box<SupportTicketModel> _supportTicketBox;
  late Box<NotificationModel> _notificationBox;
  late Box<AppSettingsModel> _appSettingsBox;
  late Box<DownloadedAudioModel> _downloadBox;

  bool _isInitialized = false;

  bool get isInitialized => _isInitialized;

  // Getters for boxes
  Box<UserModel> get userBox => _userBox;
  Box<RecentPlayModel> get recentPlayBox => _recentPlayBox;
  Box<BookmarkModel> get bookmarkBox => _bookmarkBox;
  Box<SupportTicketModel> get supportTicketBox => _supportTicketBox;
  Box<NotificationModel> get notificationBox => _notificationBox;
  Box<AppSettingsModel> get appSettingsBox => _appSettingsBox;
  Box<DownloadedAudioModel> get downloadBox => _downloadBox;

  /// Initialize Hive and all boxes
  /// Optional: provide a custom path for Hive storage
  Future<void> init({String? hivePath}) async {
    if (_isInitialized) return;

    try {
      // Initialize Hive Flutter with optional custom path
      if (hivePath != null) {
        await Hive.initFlutter(hivePath);
      } else {
        await Hive.initFlutter();
      }

      // Register adapters
      _registerAdapters();

      // Open boxes
      await _openBoxes();

      _isInitialized = true;
      print('✅ HiveDatabase initialized successfully');
    } catch (e, stackTrace) {
      print('❌ Error initializing HiveDatabase: $e\n$stackTrace');
      rethrow;
    }
  }

  /// Register all Hive adapters
  /// Register all Hive adapters
  /// NOTE: These adapters are generated by build_runner.
  /// Run: flutter pub run build_runner build
  void _registerAdapters() {
    try {
      if (!Hive.isAdapterRegistered(0)) {
        Hive.registerAdapter(DownloadedAudioModelAdapter());
      }
    } catch (e) {
      debugPrint(
        'Warning: DownloadedAudioModelAdapter not generated yet. Run build_runner.',
      );
    }
    try {
      if (!Hive.isAdapterRegistered(1)) {
        Hive.registerAdapter(UserModelAdapter());
      }
    } catch (e) {
      debugPrint(
        'Warning: UserModelAdapter not generated yet. Run build_runner.',
      );
    }
    try {
      if (!Hive.isAdapterRegistered(2)) {
        Hive.registerAdapter(RecentPlayModelAdapter());
      }
    } catch (e) {
      debugPrint(
        'Warning: RecentPlayModelAdapter not generated yet. Run build_runner.',
      );
    }
    try {
      if (!Hive.isAdapterRegistered(3)) {
        Hive.registerAdapter(BookmarkModelAdapter());
      }
    } catch (e) {
      debugPrint(
        'Warning: BookmarkModelAdapter not generated yet. Run build_runner.',
      );
    }
    try {
      if (!Hive.isAdapterRegistered(4)) {
        Hive.registerAdapter(SupportTicketModelAdapter());
      }
    } catch (e) {
      debugPrint(
        'Warning: SupportTicketModelAdapter not generated yet. Run build_runner.',
      );
    }
    try {
      if (!Hive.isAdapterRegistered(5)) {
        Hive.registerAdapter(NotificationModelAdapter());
      }
    } catch (e) {
      debugPrint(
        'Warning: NotificationModelAdapter not generated yet. Run build_runner.',
      );
    }
    try {
      if (!Hive.isAdapterRegistered(6)) {
        Hive.registerAdapter(AppSettingsModelAdapter());
      }
    } catch (e) {
      debugPrint(
        'Warning: AppSettingsModelAdapter not generated yet. Run build_runner.',
      );
    }
  }

  /// Open all Hive boxes
  Future<void> _openBoxes() async {
    _userBox = await Hive.openBox<UserModel>(userBoxName);
    _recentPlayBox = await Hive.openBox<RecentPlayModel>(recentPlayBoxName);
    _bookmarkBox = await Hive.openBox<BookmarkModel>(bookmarkBoxName);
    _supportTicketBox = await Hive.openBox<SupportTicketModel>(
      supportTicketBoxName,
    );
    _notificationBox = await Hive.openBox<NotificationModel>(
      notificationBoxName,
    );
    _appSettingsBox = await Hive.openBox<AppSettingsModel>(appSettingsBoxName);
    _downloadBox = await Hive.openBox<DownloadedAudioModel>(downloadBoxName);
  }

  /// Clear all boxes
  Future<void> clearAll() async {
    await Future.wait([
      _userBox.clear(),
      _recentPlayBox.clear(),
      _bookmarkBox.clear(),
      _supportTicketBox.clear(),
      _notificationBox.clear(),
      _appSettingsBox.clear(),
      _downloadBox.clear(),
    ]);
    print('✅ All Hive boxes cleared');
  }

  /// Clear specific box
  Future<void> clearBox(String boxName) async {
    switch (boxName) {
      case userBoxName:
        await _userBox.clear();
        break;
      case recentPlayBoxName:
        await _recentPlayBox.clear();
        break;
      case bookmarkBoxName:
        await _bookmarkBox.clear();
        break;
      case supportTicketBoxName:
        await _supportTicketBox.clear();
        break;
      case notificationBoxName:
        await _notificationBox.clear();
        break;
      case appSettingsBoxName:
        await _appSettingsBox.clear();
        break;
      case downloadBoxName:
        await _downloadBox.clear();
        break;
    }
    print('✅ Box cleared: $boxName');
  }

  /// Close all boxes
  Future<void> close() async {
    await Hive.close();
    _isInitialized = false;
    print('✅ HiveDatabase closed');
  }
}
